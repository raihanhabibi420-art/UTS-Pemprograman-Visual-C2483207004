    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed
       try {
    String nama = txtNamaBarang.getText();
    int harga = Integer.parseInt(txtHarga.getText());
    int jumlah = Integer.parseInt(txtJumlah.getText());

    if (nama.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Nama barang harus diisi!");
        return;
    }

    if (harga < 0 || jumlah <= 0) {
        JOptionPane.showMessageDialog(this, "Harga tidak boleh negatif dan jumlah harus lebih dari 0!");
        return;
    }

    int total = harga * jumlah;
    lblTotal.setText("Total Harga : Rp" + total);

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Harga dan jumlah harus berupa angka!");
} // TODO add your handling code here:
    }//GEN-LAST:event_btnHitungActionPerformed

    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
try {
    int harga = Integer.parseInt(txtHarga.getText());
    int jumlah = Integer.parseInt(txtJumlah.getText());
    int pembayaran = Integer.parseInt(txtPembayaran.getText());

    int total = harga * jumlah;
    int kembalian = pembayaran - total;

    if (txtNamaBarang.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Nama barang harus diisi!");
        return;
    }

    if (harga < 0 || jumlah <= 0 || pembayaran < 0) {
        JOptionPane.showMessageDialog(this, "Masukkan angka yang benar!");
        return;
    }

    if (pembayaran < total) {
        JOptionPane.showMessageDialog(this,
            "Pembayaran kurang Rp" + Math.abs(kembalian));
        lblKembalian.setText("Uang Kembalian : Rp0");
    } else {
        lblKembalian.setText("Uang Kembalian : Rp" + kembalian);
    }

    lblTotal.setText("Total Harga : Rp" + total);

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
        "Harga, jumlah, dan pembayaran harus diisi dengan angka!");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnBayarActionPerformed

